package com.example.clarity.data.local.dao

const val WALLET_BALANCE_SQL = """SELECT COALESCE(SUM(value / 1000000000), 0) AS high, COALESCE(SUM(value % 1000000000), 0) AS low FROM (SELECT CASE WHEN t.type = 'INCOME' THEN t.amountMinor ELSE -t.amountMinor END AS value FROM transactions t INNER JOIN wallet_cash_links w ON t.id = w.transactionId AND t.userId = w.userId WHERE t.userId = :uid AND t.isDeleted = 0 UNION ALL SELECT amountMinor AS value FROM wallet_top_ups WHERE userId = :uid UNION ALL SELECT amountMinor AS value FROM wallet_adjustments WHERE userId = :uid)"""

const val WALLET_ACCOUNT_TOTALS_SQL = """SELECT a.*, COALESCE(w.high,0) AS high, COALESCE(w.low,0) AS low FROM wallet_bank_accounts a LEFT JOIN (SELECT bankAccountId, SUM(amountMinor / 1000000000) AS high, SUM(amountMinor % 1000000000) AS low FROM wallet_top_ups WHERE userId = :uid GROUP BY bankAccountId) w ON a.id = w.bankAccountId WHERE a.userId = :uid ORDER BY a.isDefault DESC, a.name, a.id"""

const val WALLET_RECENT_ACTIVITY_SQL = """SELECT * FROM (SELECT 'cash:' || t.id AS id, t.category AS title, CASE WHEN t.type = 'INCOME' THEN t.amountMinor ELSE -t.amountMinor END AS amountMinor, t.dateEpochMillis, t.type AS kind, t.id AS transactionId, NULL AS bankAccountId FROM transactions t INNER JOIN wallet_cash_links w ON t.id = w.transactionId AND t.userId = w.userId WHERE t.userId = :uid AND t.isDeleted = 0 UNION ALL SELECT 'transfer:' || id AS id, CASE WHEN automatic = 1 THEN 'Automatic top-up' ELSE 'Bank to cash wallet' END AS title, amountMinor, dateEpochMillis, 'TRANSFER' AS kind, NULL AS transactionId, bankAccountId FROM wallet_top_ups WHERE userId = :uid UNION ALL SELECT 'adjustment:' || id AS id, note AS title, amountMinor, dateEpochMillis, 'ADJUSTMENT' AS kind, NULL AS transactionId, NULL AS bankAccountId FROM wallet_adjustments WHERE userId = :uid) ORDER BY dateEpochMillis DESC, id DESC LIMIT 50"""

const val WALLET_TOP_UP_HISTORY_SQL = """SELECT 'transfer:' || id AS id, CASE WHEN automatic = 1 THEN 'Automatic top-up' ELSE 'Bank to cash wallet' END AS title, amountMinor, dateEpochMillis, 'TRANSFER' AS kind, NULL AS transactionId, bankAccountId FROM wallet_top_ups WHERE userId = :uid ORDER BY dateEpochMillis DESC, id DESC LIMIT 50"""

